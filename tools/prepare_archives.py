# A few classes also contain unused CONSTANT_Class entries named c/dg. Do not
# replace their UTF8 entries: the same entries are reused as *field names*.
# Unused constants are not resolved when the class is loaded.
DESCRIPTOR_CLASS = re.compile(rb"L([a-z][a-z0-9_$]*);")


def constant_pool_strings(class_file: bytes):
    """Yield (index, raw_bytes) for CONSTANT_Utf8 entries."""
    if class_file[:4] != b"\xca\xfe\xba\xbe":
        raise ValueError("Not a Java class file")
    count = struct.unpack_from(">H", class_file, 8)[0]
    offset = 10
    index = 1
    while index < count:
        tag = class_file[offset]
        if tag == 1:
            length = struct.unpack_from(">H", class_file, offset + 1)[0]
            end = offset + 3 + length
            if end > len(class_file):
                raise ValueError("Truncated constant pool")
            yield index, class_file[offset + 3 : end]
            offset = end
        elif tag in (3, 4, 9, 10, 11, 12, 17, 18):
            offset += 5
        elif tag in (5, 6):
            offset += 9
            index += 1
        elif tag in (7, 8, 16, 19, 20):
            offset += 3
        elif tag == 15:
            offset += 4
        else:
            raise ValueError(f"Unknown constant-pool tag {tag}")
        index += 1
    if offset > len(class_file):
        raise ValueError("Truncated class file")


def fix_class_file(class_file: bytes, owner: str) -> tuple[bytes, int]:
    """Rewrite UTF8 constant-pool entries, preserving all non-CP bytes."""
    if class_file[:4] != b"\xca\xfe\xba\xbe":
        raise ValueError(f"Not a Java class file: {owner}")
    count = struct.unpack_from(">H", class_file, 8)[0]
    output = bytearray(class_file[:10])
    offset = 10
    index = 1
    changes = 0
    while index < count:
        tag = class_file[offset]
        if tag == 1:
            length = struct.unpack_from(">H", class_file, offset + 1)[0]
            data = class_file[offset + 3 : offset + 3 + length]
            if len(data) != length:
                raise ValueError(f"Truncated UTF8 constant in {owner}")

            def rename(match: re.Match[bytes]) -> bytes:
                name = match.group(1).decode("ascii")
                replacement = CLASS_ALIASES.get(name)
                return b"L" + replacement.encode("ascii") + b";" if replacement else match.group(0)

            new = DESCRIPTOR_CLASS.sub(rename, data)
            if new != data:
                changes += 1
            if len(new) > 65535:
                raise ValueError(f"Oversized constant in {owner}")
            output.extend(b"\x01" + struct.pack(">H", len(new)) + new)
            offset += 3 + length
        else:
            sizes = {3: 5, 4: 5, 5: 9, 6: 9, 7: 3, 8: 3, 9: 5, 10: 5, 11: 5,
                     12: 5, 15: 4, 16: 3, 17: 5, 18: 5, 19: 3, 20: 3}
            if tag not in sizes:
                raise ValueError(f"Unknown constant-pool tag {tag} in {owner}")
            size = sizes[tag]
            output.extend(class_file[offset : offset + size])
            offset += size
            if tag in (5, 6):
                index += 1
        index += 1
    output.extend(class_file[offset:])
    return bytes(output), changes


def prepare_zelith(source_jar: bytes, destination: Path) -> tuple[int, int]:
    patched = 0
    changes = 0
    with zipfile.ZipFile(io.BytesIO(source_jar)) as original, zipfile.ZipFile(
        destination, "w", compression=zipfile.ZIP_DEFLATED
    ) as output:
        names = set(original.namelist())
        missing = set(CLASS_ALIASES.values()) - {n[:-6] for n in names if n.endswith(".class")}
        if missing:
            raise ValueError(f"Expected renamed classes not found: {sorted(missing)}")
        for name in original.namelist():
            data = original.read(name)
            if name.endswith(".class"):
                data, count = fix_class_file(data, name[:-6])
                if count:
                    patched += 1
                    changes += count
            info = zipfile.ZipInfo(name, (1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            output.writestr(info, data)
    return patched, changes


def prepare(output_directory: Path) -> tuple[Path, Path]:
    output_directory.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(ZELITH_ZIP) as source:
        patched, changes = prepare_zelith(source.read(ZELITH_ENTRY), output_directory / "zelith-named.jar")
        (output_directory / "mappings-used.tiny").write_bytes(source.read("mappings-used.tiny"))
    with zipfile.ZipFile(ASYNC_ZIP) as source:
        (output_directory / "async-named.jar").write_bytes(source.read(ASYNC_ENTRY))
    generate(output_directory / "generated")
    print(f"Prepared Zelith ({patched} classes, {changes} constants repaired), Async Locator and Combat modules in {output_directory}")
    return output_directory / "zelith-named.jar", output_directory / "async-named.jar"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "build" / "prepared")
    args = parser.parse_args()
    prepare(args.output)
