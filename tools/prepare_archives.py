#!/usr/bin/env python3
"""Prepare the two supplied decompiler archives for the Fabric build.

The decompiler renamed Zelith's classes, but left their *old* names in field
and method descriptors. For example, Category.class declares fields of type
Lg; even though g.class no longer exists. This fixes those descriptors without
executing either untrusted JAR. It does not attempt to compile the decompiled
Java (which also contains names/overloads Java cannot express).

Only constant-pool UTF8 entries change in the uploaded classes; their bytecode,
stack maps and unknown attributes are copied byte-for-byte. Separate minimal
Combat module classes are generated by generate_module.py. Loom subsequently
remaps the prepared named jars to intermediary for distribution.
"""

